"""Render the criticality catalog to docs/criticality-catalog.md.

Usage: python scripts/render_catalog.py [output.md]

The document is generated from src/detector/criticality.py so the published
referential never drifts from the code; a unit test fails when it is stale.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src" / "detector"))

import criticality  # noqa: E402

DEFAULT_OUTPUT = ROOT / "docs" / "criticality-catalog.md"


def _escalation_text(rule) -> str:
    if rule.escalate is None:
        return ""
    return (rule.escalate.__doc__ or "").strip().splitlines()[0]


def _techniques(rule) -> str:
    return "<br>".join(
        f"[{tid}]({criticality.technique_url(tid)}) {criticality.TECHNIQUES[tid]}"
        for tid in rule.techniques
    )


def _stratus(rule) -> str:
    return "<br>".join(f"`{technique}`" for technique in rule.stratus)


def _row(rule) -> str:
    actions = "<br>".join(f"`{action}`" for action in rule.actions) or "any action"
    cells = [
        rule.rule_id,
        rule.level,
        rule.tactic,
        rule.title,
        actions,
        _techniques(rule),
        _stratus(rule),
        _escalation_text(rule),
    ]
    return "| " + " | ".join(cells) + " |"


def render() -> str:
    lines = [
        "# Criticality catalog",
        "",
        "<!-- Generated by scripts/render_catalog.py from src/detector/criticality.py."
        " Do not edit by hand: run `make catalog-doc`. -->",
        "",
        "ClickOps Sentinel rates every console change against this catalog before",
        "the AI investigation runs. The rating is deterministic, works without",
        "Bedrock, and acts as a floor under the agent's security severity: the",
        "agent can raise it from context, never lower it, and expresses whether",
        "a risky change looks sanctioned through its verdict instead.",
        "",
        "## Scale",
        "",
        "| Level | Meaning | Expected response |",
        "| --- | --- | --- |",
    ]
    for level in reversed(criticality.LEVELS):
        lines.append(
            f"| {level} | {criticality.SCALE[level]} | {criticality.RESPONSE[level]} |"
        )
    lines += [
        "",
        "## How a rating is computed",
        "",
        "1. The CloudTrail `eventSource` and `eventName` form a `service:Action` key",
        "   (version suffixes such as `20150331v2` are stripped), matched against",
        "   the rules below.",
        "2. The rule's parameter check, when it has one, inspects",
        "   `requestParameters` and can only raise the level.",
        "3. Modifiers raise the level further: actions by the root user",
        f"   ({criticality.ROOT_RULE.rule_id}) and actions that target ClickOps",
        f"   Sentinel's own resources ({criticality.SELF_RULE.rule_id}) are at least",
        f"   {criticality.ROOT_RULE.level}, and apply even when no rule matches.",
        "4. A failed call (any `errorCode`) is lowered one level, never below low,",
        "   and marked as an attempt.",
        "5. Critical changes bypass the session cooldown, so they are always",
        "   investigated on their own.",
        "",
        "Operators can re-rate actions with the `CriticalityOverrides` stack",
        "parameter, for example `ec2:CreateVpc=high,iam:CreateRole=low`. An",
        "override replaces the catalog level of that action; parameter checks",
        "still apply, so an override cannot hide a public exposure.",
        "",
        "References: [MITRE ATT&CK](https://attack.mitre.org/matrices/enterprise/cloud/iaas/)",
        f"techniques and [Stratus Red Team]({criticality.STRATUS_URL}) attack",
        "techniques, the open-source catalog of known AWS attack techniques.",
        "",
        "## Rules",
        "",
        "| ID | Level | Tactic | Rule | Actions | MITRE ATT&CK | Stratus Red Team"
        " | Parameter check |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for rule in criticality.RULES + criticality.MODIFIER_RULES:
        lines.append(_row(rule))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    output.write_text(render())
    print(f"Wrote {output} ({len(criticality.RULES)} rules)")


if __name__ == "__main__":
    main()
